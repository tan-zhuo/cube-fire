    const LANGS = { zh, en, ja };
    const STORE_KEY = 'cubefire-lang';

    function detectLang() {
        try {
            const saved = localStorage.getItem(STORE_KEY);
            if (saved && LANGS[saved]) return saved;
        } catch (e) { /* localStorage 不可用时走浏览器语言 */ }
        const nav = ((navigator.language || navigator.userLanguage || 'zh')).toLowerCase();
        if (nav.startsWith('zh')) return 'zh';
        if (nav.startsWith('ja')) return 'ja';
        return 'en';
    }

    let lang = detectLang();

    function t(key, params) {
        let s = LANGS[lang][key];
        if (s === undefined) s = zh[key];
        if (s === undefined) return key;
        if (params) {
            for (const k of Object.keys(params)) {
                s = s.split('{' + k + '}').join(String(params[k]));
            }
        }
        return s;
    }

    // 套用静态标注：data-i18n=文本、data-i18n-html=富文本（仅本词典内容，安全）、
    // data-i18n-ph=placeholder、data-i18n-title=title 属性
    function apply(root) {
        const scope = root || document;
        scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
        scope.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
        scope.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
        scope.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
        document.title = t('lp.title');
        const meta = document.querySelector('meta[name="description"]');
        if (meta) meta.content = t('lp.metaDesc');
        document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
        // 语言切换按钮高亮
        scope.querySelectorAll('.lang-switch button').forEach(btn => {
            btn.classList.toggle('active', btn.dataset.lang === lang);
        });
    }

    function setLang(next) {
        if (!LANGS[next] || next === lang) return;
        try { localStorage.setItem(STORE_KEY, next); } catch (e) { /* 忽略 */ }
        location.reload();
    }

    window.I18N = {
        get lang() { return lang; },
        t, apply, setLang,
    };

    document.addEventListener('DOMContentLoaded', () => {
        apply();
        document.querySelectorAll('.lang-switch button').forEach(btn => {
            btn.addEventListener('click', () => setLang(btn.dataset.lang));
        });
    });
